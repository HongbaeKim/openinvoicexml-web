import { createHash } from "node:crypto";
import type {
  FastifyInstance,
  FastifyPluginAsync,
  FastifyReply,
} from "fastify";
import rateLimit from "@fastify/rate-limit";

import { checkGeneratedXml } from "./xml-checks.js";
import {
  relayToValidator,
  type RelayResult,
} from "./validator-client.js";

// This plugin exposes two validation endpoints:
//
// POST /api/validate
//
// Used for XML that OpenInvoiceXML itself just generated in the browser.
// The browser sends the exact XML bytes that the user will download.
//
// The backend:
//   1. receives the raw XML bytes
//   2. calculates SHA-256 from those exact bytes
//   3. performs cheap preliminary XML checks
//   4. forwards the unchanged bytes to the internal validator service
//   5. confirms that the validator reports the same SHA-256
//
// This lets the browser know that the XML it generated and the XML that was
// externally validated are exactly the same bytes.
//
//
// POST /api/validate/upload
//
// Used when someone uploads an existing invoice file, possibly created by
// another program.
//
// The upload can be XML or PDF.
//
// The backend receives only the raw file bytes. The original file name is not
// needed or forwarded.
//
// The validator determines the actual format from the contents of the file.
// We do not trust the browser's filename or MIME type to decide whether
// something is XML or PDF.
//
//
// Privacy:
//
// Nothing from the invoice body is intentionally logged here.
// Logs contain only operational outcomes such as:
//
//   validated
//   validator-busy
//   validator-unavailable
//   rejected:too-large
//
// The invoice itself is not stored by these routes.

/**
 * Reads a positive integer from an environment variable.
 *
 * Example:
 *
 *   VALIDATE_RATE_LIMIT_PER_MINUTE=10
 *
 * If the variable is missing, invalid, zero, negative, or not an integer,
 * the supplied fallback value is used instead.
 */
function positiveInt(name: string, fallback: number): number {
  const value = Number(process.env[name] ?? fallback);

  return Number.isInteger(value) && value > 0
    ? value
    : fallback;
}

// Maximum size for XML generated by our own browser invoicing form.
//
// Default:
//   1 MiB
const MAX_XML_BYTES = positiveInt(
  "MAX_XML_BYTES",
  1024 * 1024,
);

// Maximum size for an externally uploaded XML invoice.
//
// Default:
//   5 MiB
const MAX_UPLOAD_XML_BYTES = positiveInt(
  "MAX_UPLOAD_XML_BYTES",
  5 * 1024 * 1024,
);

// Maximum size for an externally uploaded PDF invoice.
//
// PDFs can reasonably be larger than XML, so they get a separate limit.
//
// Default:
//   10 MiB
const MAX_UPLOAD_PDF_BYTES = positiveInt(
  "MAX_UPLOAD_PDF_BYTES",
  10 * 1024 * 1024,
);

// The backend waits slightly longer than the validator's own XML deadline.
//
// Example:
//
//   validator timeout: 60 seconds
//   relay timeout:     70 seconds
//
// This gives the validator time to return its own controlled "unavailable"
// response before this HTTP relay aborts the connection itself.
const RELAY_TIMEOUT_MS =
  positiveInt("VALIDATION_TIMEOUT_MS", 60_000) + 10_000;

// Uploaded files can require more work, especially PDFs with veraPDF,
// so they use a longer timeout.
//
// Default:
//
//   validator timeout: 120 seconds
//   relay timeout:     130 seconds
const UPLOAD_RELAY_TIMEOUT_MS =
  positiveInt("UPLOAD_VALIDATION_TIMEOUT_MS", 120_000) + 10_000;

/**
 * Looks only at the first five bytes to see whether the file begins
 * with the standard PDF signature:
 *
 *   %PDF-
 *
 * This is used only to choose the upload size limit.
 *
 * It is NOT the final file-format decision.
 *
 * The validator service later inspects the full file and decides whether the
 * content is really XML, PDF, or unsupported.
 */
function isPdf(bytes: Buffer): boolean {
  return bytes
    .subarray(0, 5)
    .toString("latin1") === "%PDF-";
}

/**
 * Returns only the media type portion of a Content-Type header.
 *
 * Example:
 *
 *   application/xml; charset=utf-8
 *
 * becomes:
 *
 *   application/xml
 *
 * It also normalizes casing and surrounding whitespace.
 */
function mediaType(header: string | undefined): string {
  return (
    (header ?? "")
      .split(";")[0]
      ?.trim()
      .toLowerCase() ?? ""
  );
}

/**
 * Calculates the SHA-256 fingerprint of the exact request bytes.
 *
 * The resulting hexadecimal string is later compared with the hash returned
 * by the validator service.
 */
function sha256(bytes: Buffer): string {
  return createHash("sha256")
    .update(bytes)
    .digest("hex");
}

/**
 * Converts the internal validator result into the public API response.
 *
 * This also performs an important integrity check:
 *
 * the SHA-256 reported by the validator must exactly match the SHA-256 that
 * this backend calculated from the bytes it originally received.
 */
export function sendRelayResult(
  reply: FastifyReply,
  relay: RelayResult,
  expectedSha256: string,
): FastifyReply {
  // The validator service is alive and reachable, but currently has no
  // available validation capacity.
  //
  // Return HTTP 503 and preserve Retry-After so the frontend can wait and
  // retry instead of immediately treating this as a permanent failure.
  if (relay.kind === "busy") {
    reply.log.info(
      { outcome: "validator-busy" },
      "validation",
    );

    return reply
      .code(503)
      .header("retry-after", relay.retryAfter)
      .send({ error: "busy" });
  }

  // The validator could not produce a usable validation response.
  //
  // This can represent things such as:
  //   - validator service down
  //   - network failure
  //   - internal timeout
  //   - unexpected validator HTTP response
  //
  // Do not expose internal details to the public client.
  if (relay.kind === "unavailable") {
    reply.log.warn(
      { outcome: "validator-unavailable" },
      "validation",
    );

    return reply
      .code(503)
      .send({ error: "validation unavailable" });
  }

  // The validator returned success, but it claims to have validated different
  // bytes from the ones this backend received.
  //
  // This should never happen during normal operation.
  //
  // Treat it as an internal validation failure rather than returning potentially
  // misleading validation results to the user.
  if (relay.body.sha256 !== expectedSha256) {
    reply.log.error(
      { outcome: "relay-mismatch" },
      "validation",
    );

    return reply
      .code(503)
      .send({ error: "validation unavailable" });
  }

  // The validator successfully checked the same bytes that we received.
  reply.log.info(
    { outcome: "validated" },
    "validation",
  );

  return reply
    .code(200)
    .send(relay.body);
}

/**
 * Fastify plugin containing the public invoice-validation API.
 *
 * Rate limiting and raw-byte parsers are registered inside this plugin so they
 * remain scoped to these invoicing routes instead of changing unrelated API
 * behavior.
 */
export const invoicingRoutes: FastifyPluginAsync = async (
  app: FastifyInstance,
) => {
  // Enable @fastify/rate-limit for this plugin, but do not apply one global
  // limit automatically to every route.
  //
  // Individual endpoints below define their own limits.
  await app.register(rateLimit, {
    global: false,
  });

  // Accept generated XML as raw bytes.
  //
  // parseAs: "buffer" means Fastify does not parse or transform the XML.
  //
  // The route receives the exact original bytes, which is important because
  // those same bytes are hashed and forwarded to the validator.
  app.addContentTypeParser(
    "application/xml",
    {
      parseAs: "buffer",
      bodyLimit: MAX_XML_BYTES,
    },
    (_request, body, done) => {
      done(null, body);
    },
  );

  // Accept uploaded invoice files as raw bytes.
  //
  // application/octet-stream is used regardless of whether the actual content
  // is XML or PDF.
  //
  // This parser needs one outer body limit before we have inspected the file,
  // so it uses the larger of the XML and PDF limits.
  //
  // The route later applies the correct format-specific limit.
  app.addContentTypeParser(
    "application/octet-stream",
    {
      parseAs: "buffer",
      bodyLimit: Math.max(
        MAX_UPLOAD_XML_BYTES,
        MAX_UPLOAD_PDF_BYTES,
      ),
    },
    (_request, body, done) => {
      done(null, body);
    },
  );

  /**
   * Validate XML generated by OpenInvoiceXML itself.
   *
   * Expected request:
   *
   *   POST /api/validate
   *   Content-Type: application/xml
   *   Body: raw XML bytes
   */
  app.post<{ Body: Buffer }>(
    "/api/validate",
    {
      config: {
        rateLimit: {
          // Default:
          //
          // one client may request up to 6 generated-invoice validations
          // per minute.
          //
          // This can be overridden with:
          //
          //   VALIDATE_RATE_LIMIT_PER_MINUTE
          max: positiveInt(
            "VALIDATE_RATE_LIMIT_PER_MINUTE",
            6,
          ),
          timeWindow: "1 minute",
        },
      },
    },
    async (request, reply) => {
      const body = request.body;

      // This endpoint accepts only application/xml.
      //
      // Also verify that the content-type parser actually produced a Buffer.
      if (
        mediaType(request.headers["content-type"]) !==
          "application/xml" ||
        !Buffer.isBuffer(body)
      ) {
        return reply
          .code(415)
          .send({
            error: "expected application/xml",
          });
      }

      // Calculate the fingerprint before forwarding anything.
      //
      // This hash belongs to the exact bytes received from the browser.
      const hash = sha256(body);

      // Perform cheap local checks before spending validator capacity.
      //
      // Examples include:
      //   - empty input
      //   - invalid UTF-8
      //   - DOCTYPE
      //   - malformed XML
      //   - wrong root element / namespace
      //
      // Passing this check does NOT mean that the invoice is compliant.
      // KoSIT and Mustang still perform the real external validation.
      const failure = checkGeneratedXml(body);

      if (failure) {
        // Record only the rejection category.
        //
        // Do not log XML contents.
        request.log.info(
          {
            outcome: `rejected:${failure}`,
          },
          "validation",
        );

        return reply
          .code(400)
          .send({
            error: failure,
          });
      }

      // Forward the exact unchanged XML bytes to the internal validator.
      //
      // sendRelayResult then:
      //   - handles busy/unavailable states
      //   - verifies the returned SHA-256
      //   - sends the validation result to the browser
      return sendRelayResult(
        reply,
        await relayToValidator(
          "/xml",
          body,
          RELAY_TIMEOUT_MS,
        ),
        hash,
      );
    },
  );

  /**
   * Validate an existing invoice uploaded by the user.
   *
   * Expected request:
   *
   *   POST /api/validate/upload
   *   Content-Type: application/octet-stream
   *   Body: raw XML or PDF bytes
   */
  app.post<{ Body: Buffer }>(
    "/api/validate/upload",
    {
      config: {
        rateLimit: {
          // Uploaded files may be larger and more expensive to validate,
          // especially PDFs, so this endpoint has a lower default limit:
          //
          //   3 uploads per client per minute.
          //
          // Override with:
          //
          //   UPLOAD_RATE_LIMIT_PER_MINUTE
          max: positiveInt(
            "UPLOAD_RATE_LIMIT_PER_MINUTE",
            3,
          ),
          timeWindow: "1 minute",
        },
      },
    },
    async (request, reply) => {
      const body = request.body;

      // The public client always sends uploaded files as raw binary data.
      //
      // We deliberately do not use the client-provided Content-Type to decide
      // whether the contents are XML or PDF.
      const type = mediaType(
        request.headers["content-type"],
      );

      if (
        type !== "application/octet-stream" ||
        !Buffer.isBuffer(body)
      ) {
        return reply
          .code(415)
          .send({
            error: "expected application/octet-stream",
          });
      }

      // Reject an upload containing zero bytes.
      if (body.length === 0) {
        return reply
          .code(400)
          .send({
            error: "empty",
          });
      }

      // Look at the PDF magic bytes only to choose the appropriate size limit.
      //
      // This is not trusted as final format detection.
      const limit = isPdf(body)
        ? MAX_UPLOAD_PDF_BYTES
        : MAX_UPLOAD_XML_BYTES;

      if (body.length > limit) {
        request.log.info(
          {
            outcome: "rejected:too-large",
          },
          "validation",
        );

        return reply
          .code(413)
          .send({
            error: "too large",
          });
      }

      // Fingerprint the exact uploaded file before forwarding it.
      const hash = sha256(body);

      // Send the untouched bytes to the validator's generic file endpoint.
      //
      // The validator itself determines whether the content is XML or PDF and
      // runs the appropriate external validation tools.
      return sendRelayResult(
        reply,
        await relayToValidator(
          "/file",
          body,
          UPLOAD_RELAY_TIMEOUT_MS,
        ),
        hash,
      );
    },
  );
};