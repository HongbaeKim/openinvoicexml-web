import { XMLValidator } from "fast-xml-parser";

// Cheap checks before a generated invoice is forwarded to the validator service.
//
// Important: all checks below work on a decoded COPY of the request body.
// The original bytes are never modified, normalized, parsed into another structure,
// or re-encoded before hashing and external validation.
//
// That means:
//   1. SHA-256 is calculated from the exact bytes sent by the browser.
//   2. KoSIT / Mustang receive those same original bytes.
//   3. These checks cannot accidentally change the document being validated.
//
// This endpoint is intentionally narrow. It only accepts the kind of XML produced by
// the browser invoice form: an XRechnung UBL Invoice.
//
// It is therefore not exposed as a general-purpose XML validation endpoint.
//
// DOCTYPE is rejected before the document reaches the Java validators. This prevents
// documents using external entities or entity expansion from being passed further on.

export type XmlCheckFailure =
  | "empty"
  | "not-utf8"
  | "doctype"
  | "not-well-formed"
  | "not-ubl-invoice";

// Namespace expected for a UBL 2.x Invoice root element.
//
// A normal generated invoice starts approximately like:
//
// <Invoice
//   xmlns="urn:oasis:names:specification:ubl:schema:xsd:Invoice-2"
//   ...
// >
const UBL_INVOICE_NS =
  "urn:oasis:names:specification:ubl:schema:xsd:Invoice-2";

/**
 * Reads only enough of the XML text to identify the root element.
 *
 * Returns:
 *   - localName: the root element name without its prefix, for example "Invoice"
 *   - namespace: the namespace declared for that root element
 *
 * Returns null if no root start tag can be found.
 *
 * This is not used to validate the whole XML document. Full well-formedness is checked
 * separately with XMLValidator before this function is called.
 */
function rootElement(
  text: string,
): { localName: string; namespace: string | undefined } | null {
  // XML can contain some content before the actual root element, for example:
  //
  //   <?xml version="1.0" encoding="UTF-8"?>
  //   <!-- comment -->
  //   <?some-processing-instruction?>
  //
  // Skip those items, together with surrounding whitespace, so that the next tag
  // should be the document's root element.
  const prolog =
    /^(?:\s+|<\?[\s\S]*?\?>|<!--[\s\S]*?-->)*?/.exec(text);

  const rest = text.slice(prolog?.[0].length ?? 0);

  // Match the root start tag.
  //
  // Supports both forms:
  //
  //   <Invoice ...>
  //
  // and:
  //
  //   <ubl:Invoice ...>
  //
  // Capture groups:
  //   tag[1] = optional prefix, for example "ubl"
  //   tag[2] = local name, for example "Invoice"
  //   tag[3] = raw attributes inside the start tag
  const tag =
    /^<(?:([A-Za-z_][\w.-]*):)?([A-Za-z_][\w.-]*)([^>]*)>/.exec(rest);

  if (!tag) return null;

  const [, prefix, localName = "", attributes = ""] = tag;

  // If the root uses a prefix such as:
  //
  //   <ubl:Invoice xmlns:ubl="...">
  //
  // then we must look for xmlns:ubl.
  //
  // If it has no prefix:
  //
  //   <Invoice xmlns="...">
  //
  // then we look for the default xmlns declaration.
  const nsAttribute = prefix ? `xmlns:${prefix}` : "xmlns";

  let namespace: string | undefined;

  // Read attributes from the root start tag and find the namespace declaration
  // that belongs to the root element.
  //
  // Supports both:
  //
  //   xmlns="..."
  //
  // and:
  //
  //   xmlns='...'
  for (const match of attributes.matchAll(
    /([\w:.-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g,
  )) {
    if (match[1] === nsAttribute) {
      namespace = match[2] ?? match[3];
    }
  }

  return { localName, namespace };
}

/**
 * Performs lightweight checks on XML generated by the browser before the document
 * is sent to the external validator service.
 *
 * Returns:
 *   null                  -> accepted by these preliminary checks
 *   XmlCheckFailure value -> rejected, with the reason
 *
 * Passing this function does NOT mean that the invoice is XRechnung-compliant.
 * KoSIT / Mustang still perform the actual invoice validation afterwards.
 */
export function checkGeneratedXml(
  bytes: Uint8Array,
): XmlCheckFailure | null {
  // An invoice document must contain at least one byte.
  if (bytes.length === 0) {
    return "empty";
  }

  let text: string;

  try {
    // Decode a temporary copy as strict UTF-8.
    //
    // fatal: true means malformed UTF-8 causes an exception instead of silently
    // replacing invalid bytes with the Unicode replacement character U+FFFD.
    //
    // TextDecoder also removes a leading UTF-8 BOM from this decoded copy.
    // The original byte array itself remains untouched.
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return "not-utf8";
  }

  // Reject any XML document containing a DOCTYPE declaration.
  //
  // The generated browser invoices never need DOCTYPE, so there is no legitimate
  // reason to accept one here.
  //
  // Rejecting it also ensures that XML using entities or external entity references
  // is never forwarded to the Java-based validator tools.
  if (/<!DOCTYPE/i.test(text)) {
    return "doctype";
  }

  // Check basic XML syntax:
  // matching tags, valid nesting, correctly formed attributes, etc.
  //
  // This is only an XML well-formedness check. It does not check XRechnung rules.
  if (XMLValidator.validate(text) !== true) {
    return "not-well-formed";
  }

  // The browser-generated endpoint is expected to receive a UBL Invoice only.
  //
  // Examples that should be rejected here:
  //   <CreditNote ...>
  //   <Invoice xmlns="some-other-namespace">
  //   <foo:Invoice xmlns:foo="some-other-namespace">
  const root = rootElement(text);

  if (
    root?.localName !== "Invoice" ||
    root.namespace !== UBL_INVOICE_NS
  ) {
    return "not-ubl-invoice";
  }

  // The document passed the cheap preliminary checks.
  //
  // It still needs the real external validation afterwards.
  return null;
}
